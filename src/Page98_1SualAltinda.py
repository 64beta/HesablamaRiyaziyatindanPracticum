n = 4
x = [0.0] * (n + 1)
y = [0.0] * (n + 1)
y1 = [0.0] * (n + 1)

h = float(input())

for i in range(n + 1):
    x[i] = float(input())
    y[i] = float(input())

y1[0] = (-25 * y[0] + 48 * y[1] - 36 * y[2] + 16 * y[3] - 3 * y[4]) / (12 * h)
y1[1] = (-3 * y[0] + 10 * y[1] + 18 * y[2] + 6 * y[3] + y[4]) / (12 * h)
y1[2] = (y[0] - 8 * y[1] + 8 * y[3] - y[4]) / (12 * h)
y1[3] = (-y[0] + 6 * y[1] - 18 * y[2] + 10 * y[3] + 3 * y[4]) / (12 * h)
y1[4] = (3 * y[0] - 16 * y[1] + 36 * y[2] - 48 * y[3] + 25 * y[4]) / (12 * h)

for i in range(n + 1):
    print(f"x{i} = {x[i]:5.3f}   y{i} = {y1[i]:20.10f}")
